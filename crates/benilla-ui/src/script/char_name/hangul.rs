/// Whether `unit` is one of the client's 2,350 syllables.
pub(super) fn is_listed(unit: u16) -> bool {
    if !(FIRST..=LAST).contains(&unit) {
        return false;
    }
    let n = usize::from(unit - FIRST);
    BITMAP[n / 64] >> (n % 64) & 1 == 1
}

#[cfg(test)]
mod tests {
    use super::*;

    /// 2,350 syllables, the first and last of the list, with the block's own ends and its
    /// unlisted neighbours outside.
    #[test]
    fn the_bitmap_holds_the_korean_standards_2350_syllables() {
        let count = (FIRST..=LAST).filter(|&u| is_listed(u)).count();
        assert_eq!(count, 2350);
        assert!(is_listed(0xac00), "가, the first");
        assert!(is_listed(0xd79d), "힝, the last of the list");
        assert!(!is_listed(0xd79e), "힞, past it");
        assert!(!is_listed(LAST), "힣, the block's last, is not listed");
        assert!(is_listed(0xac01), "각 is listed");
        assert!(!is_listed(0xac02), "갂 is in the block but not the list");
        assert!(!is_listed(0xabff) && !is_listed(0xd7a4));
        // 한글, each in EUC-KR.
        assert!(is_listed(0xd55c) && is_listed(0xae00));
    }
}
